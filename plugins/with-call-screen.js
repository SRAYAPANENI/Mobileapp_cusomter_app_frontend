const fs = require('fs');
const path = require('path');
const { withAndroidManifest, withMainActivity, withMainApplication, withDangerousMod } = require('expo/config-plugins');

// An incoming call must be able to appear over the lock screen and switch
// the screen on — the way WhatsApp's does (docs/CALLING_SYSTEM.md, B4/B5).
//
// 1. MainActivity shows over the lock screen and turns the screen on ONLY
//    while a call notification is showing (incoming ring or ongoing call).
//    Setting these permanently in the manifest would put the whole app over
//    the lock screen whenever it was the last thing open — a security hole.
// 2. CallScreenModule lets JS check Android 14's full-screen-intent
//    permission (not granted by default to apps that aren't dialers) and
//    open its settings page.
// 3. The incoming-call notification itself, as Android's CallStyle (real
//    green Answer / red Decline buttons, treated by the OS as a call) —
//    services/callManager.ts calls CallStyleModule.showIncoming/cancel.
//    Answer and a tap open the app (MainActivity hands the action to JS via
//    CallActionModule, queued until JS is ready). Decline goes to
//    CallActionReceiver: to JS if it's running, otherwise to the
//    DodorezCallDecline headless task (registered in index.js).
//
// Channel ids must match services/callManager.ts.
const CALL_CHANNELS = ['incoming_calls_v7', 'ongoing_calls_v1'];
const MARKER = '// dodorez:call-lock-screen';

const ACTIVITY_CODE = `
  ${MARKER}
  private fun applyCallLockScreenFlags() {
    if (Build.VERSION.SDK_INT < Build.VERSION_CODES.O_MR1) return
    val manager = getSystemService(android.app.NotificationManager::class.java) ?: return
    val callShowing = manager.activeNotifications.any {
      it.notification.channelId in setOf(${CALL_CHANNELS.map((c) => `"${c}"`).join(', ')})
    }
    setShowWhenLocked(callShowing)
    setTurnScreenOn(callShowing)
  }

  override fun onResume() {
    super.onResume()
    applyCallLockScreenFlags()
  }

  override fun onNewIntent(intent: android.content.Intent) {
    super.onNewIntent(intent)
    CallActionModule.handleIntent(this, intent)
    applyCallLockScreenFlags()
  }
`;

// Inserted right after super.onCreate(): a cold start from the notification.
const ON_CREATE_CODE = `
    CallActionModule.handleIntent(this, intent)`;

