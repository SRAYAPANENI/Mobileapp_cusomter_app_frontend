function callStyleSource(pkg) {
  return `package ${pkg}

import android.app.Notification
import android.app.NotificationManager
import android.app.PendingIntent
import android.content.Context
import android.content.Intent
import android.os.Bundle
import androidx.core.app.NotificationCompat
import androidx.core.app.Person
import com.facebook.react.bridge.ReactApplicationContext
import com.facebook.react.bridge.ReactContextBaseJavaModule
import com.facebook.react.bridge.ReactMethod

// Generated by plugins/with-call-screen.js — edit there, not here.
object CallNotifications {
  // Same channel as plugins/with-call-ringtone-channel.js (the phone's ringtone).
  const val CHANNEL_ID = "${CALL_CHANNELS[0]}"
  const val NOTIFICATION_ID = 7001
  const val ACTION_ACCEPT = "${pkg}.ACCEPT_CALL"
  const val ACTION_DECLINE = "${pkg}.DECLINE_CALL"
  const val ACTION_OPEN = "${pkg}.OPEN_RINGING"
  // Matches RING_TIMEOUT_MS in services/callManager.ts.
  const val RING_TIMEOUT_MS = 55000L

  private fun tag(jobId: String) = "incoming-call-" + jobId

  private fun openApp(context: Context, action: String, extras: Bundle, requestCode: Int): PendingIntent {
    val intent = (context.packageManager.getLaunchIntentForPackage(context.packageName) ?: Intent())
      .setAction(action)
      .putExtras(extras)
      .addFlags(Intent.FLAG_ACTIVITY_NEW_TASK or Intent.FLAG_ACTIVITY_SINGLE_TOP)
    return PendingIntent.getActivity(
      context, requestCode, intent, PendingIntent.FLAG_UPDATE_CURRENT or PendingIntent.FLAG_IMMUTABLE,
    )
  }

  fun show(context: Context, jobId: String, callerName: String, callerId: String, callId: String) {
    val extras = Bundle().apply {
      putString("jobId", jobId)
      putString("callerName", callerName)
      putString("callerId", callerId)
      putString("callId", callId)
    }
    val base = jobId.hashCode()
    val answer = openApp(context, ACTION_ACCEPT, extras, base + 1)
    val open = openApp(context, ACTION_OPEN, extras, base + 2)
    val decline = PendingIntent.getBroadcast(
      context, base + 3,
      Intent(context, CallActionReceiver::class.java).setAction(ACTION_DECLINE).putExtras(extras),
      PendingIntent.FLAG_UPDATE_CURRENT or PendingIntent.FLAG_IMMUTABLE,
    )
    val caller = Person.Builder().setName(callerName).setImportant(true).build()
    val iconRes = context.resources.getIdentifier("notification_icon", "drawable", context.packageName)
      .takeIf { it != 0 } ?: context.applicationInfo.icon
    val notification = NotificationCompat.Builder(context, CHANNEL_ID)
      .setSmallIcon(iconRes)
      .setContentTitle(callerName)
      .setContentText("Incoming Dodorez call")
      .setCategory(NotificationCompat.CATEGORY_CALL)
      .setPriority(NotificationCompat.PRIORITY_MAX)
      .setVisibility(NotificationCompat.VISIBILITY_PUBLIC)
      .setOngoing(true)
      .setAutoCancel(false)
      .setTimeoutAfter(RING_TIMEOUT_MS)
      .setContentIntent(open)
      .setFullScreenIntent(open, true)
      .setStyle(NotificationCompat.CallStyle.forIncomingCall(caller, decline, answer))
      .build()
    // Keep ringing until answered, declined, cancelled or timed out.
    notification.flags = notification.flags or Notification.FLAG_INSISTENT
    context.getSystemService(NotificationManager::class.java)?.notify(tag(jobId), NOTIFICATION_ID, notification)
  }

  fun cancel(context: Context, jobId: String) {
    context.getSystemService(NotificationManager::class.java)?.cancel(tag(jobId), NOTIFICATION_ID)
  }
}

class CallStyleModule(private val reactContext: ReactApplicationContext) : ReactContextBaseJavaModule(reactContext) {
  override fun getName() = "CallStyleModule"

  @ReactMethod
  fun showIncoming(jobId: String, callerName: String, callerId: String, callId: String) {
    CallNotifications.show(reactContext, jobId, callerName, callerId, callId)
  }

  @ReactMethod
  fun cancel(jobId: String) {
    CallNotifications.cancel(reactContext, jobId)
  }
}
`;
}

function callActionSource(pkg) {
  return `package ${pkg}

import android.app.Activity
import android.content.BroadcastReceiver
import android.content.Context
import android.content.Intent
import android.os.Bundle
import android.util.Log
import com.facebook.react.HeadlessJsTaskService
import com.facebook.react.bridge.Arguments
import com.facebook.react.bridge.Promise
import com.facebook.react.bridge.ReactApplicationContext
import com.facebook.react.bridge.ReactContextBaseJavaModule
import com.facebook.react.bridge.ReactMethod
import com.facebook.react.jstasks.HeadlessJsTaskConfig
import com.facebook.react.modules.core.DeviceEventManagerModule

// Generated by plugins/with-call-screen.js — edit there, not here.
class CallActionModule(private val reactContext: ReactApplicationContext) : ReactContextBaseJavaModule(reactContext) {
  init {
    instance = this
  }

  override fun getName() = "CallActionModule"

  /** JS is listening — actions from now on are emitted live. */
  @ReactMethod
  fun markReady() {
    ready = true
  }

  /** The action that cold-started the app, if any (taken once). */
  @ReactMethod
  fun getInitialAction(promise: Promise) {
    val action = pending
    pending = null
    promise.resolve(action?.let { Arguments.fromBundle(it) })
  }

  // Required by NativeEventEmitter.
  @ReactMethod
  fun addListener(eventName: String) {}

  @ReactMethod
  fun removeListeners(count: Double) {}

  companion object {
    @Volatile private var instance: CallActionModule? = null
    @Volatile private var ready = false
    @Volatile private var pending: Bundle? = null

    /** False if JS can't take it right now. */
    fun emit(payload: Bundle): Boolean {
      val module = instance ?: return false
      if (!ready || !module.reactContext.hasActiveReactInstance()) return false
      module.reactContext
        .getJSModule(DeviceEventManagerModule.RCTDeviceEventEmitter::class.java)
        .emit("CallAction", Arguments.fromBundle(payload))
      return true
    }

    /** Answer / tap on the call notification opened the app. */
    fun handleIntent(activity: Activity, intent: Intent?) {
      val action = intent?.action ?: return
      if (action != CallNotifications.ACTION_ACCEPT && action != CallNotifications.ACTION_OPEN) return
      val payload = Bundle(intent.extras ?: Bundle()).apply { putString("action", action) }
      // Answer stops the ring here; for a tap / full-screen open, JS decides
      // (it keeps ringing while App Lock is showing).
      if (action == CallNotifications.ACTION_ACCEPT) {
        payload.getString("jobId")?.let { CallNotifications.cancel(activity, it) }
      }
      // Handled — a recreated activity mustn't answer it again.
      intent.action = Intent.ACTION_MAIN
      if (!emit(payload)) pending = payload
    }
  }
}

/** Decline on the call notification — works whether or not the app is running. */
class CallActionReceiver : BroadcastReceiver() {
  override fun onReceive(context: Context, intent: Intent) {
    val extras = intent.extras ?: return
    val jobId = extras.getString("jobId") ?: return
    CallNotifications.cancel(context, jobId)
    val payload = Bundle(extras).apply { putString("action", CallNotifications.ACTION_DECLINE) }
    if (CallActionModule.emit(payload)) return
    try {
      context.startService(Intent(context, CallDeclineTaskService::class.java).putExtras(extras))
      HeadlessJsTaskService.acquireWakeLockNow(context)
    } catch (e: Exception) {
      Log.w("CallActionReceiver", "Could not send the decline", e)
    }
  }
}

/** Runs the DodorezCallDecline JS task (index.js) when the app isn't running. */
class CallDeclineTaskService : HeadlessJsTaskService() {
  override fun getTaskConfig(intent: Intent?): HeadlessJsTaskConfig? {
    val extras = intent?.extras ?: return null
    return HeadlessJsTaskConfig("DodorezCallDecline", Arguments.fromBundle(extras), 15000, true)
  }
}
`;
}

