function withLockScreenFlags(config) {
  return withMainActivity(config, (config) => {
    let src = config.modResults.contents;
    if (src.includes(MARKER)) return config;
    if (!src.includes('import android.os.Build')) {
      src = src.replace(/(package [^\n]+\n)/, '$1\nimport android.os.Build\n');
    }
    src = src.replace(/super\.onCreate\([^)]*\)/, (m) => m + ON_CREATE_CODE);
    // Before the class's closing brace.
    const end = src.lastIndexOf('}');
    src = src.slice(0, end) + ACTIVITY_CODE + src.slice(end);
    config.modResults.contents = src;
    return config;
  });
}

function withModuleFiles(config) {
  return withDangerousMod(config, ['android', (config) => {
    const pkg = config.android.package;
    const dir = path.join(config.modRequest.platformProjectRoot, 'app/src/main/java', ...pkg.split('.'));
    fs.mkdirSync(dir, { recursive: true });
    fs.writeFileSync(path.join(dir, 'CallScreenModule.kt'), moduleSource(pkg));
    fs.writeFileSync(path.join(dir, 'CallScreenPackage.kt'), packageSource(pkg));
    fs.writeFileSync(path.join(dir, 'CallStyleModule.kt'), callStyleSource(pkg));
    fs.writeFileSync(path.join(dir, 'CallActionModule.kt'), callActionSource(pkg));
    return config;
  }]);
}

function withPackageRegistered(config) {
  return withMainApplication(config, (config) => {
    const src = config.modResults.contents;
    if (!src.includes('add(CallScreenPackage())')) {
      config.modResults.contents = src.replace(
        /PackageList\(this\)\.packages\.apply \{\r?\n/,
        (m) => `${m}              add(CallScreenPackage())\n`,
      );
    }
    return config;
  });
}

function withCallComponents(config) {
  return withAndroidManifest(config, (config) => {
    const application = config.modResults.manifest.application[0];
    const has = (list, name) => (list || []).some((x) => x.$['android:name'] === name);
    application.receiver = application.receiver || [];
    if (!has(application.receiver, '.CallActionReceiver')) {
      application.receiver.push({ $: { 'android:name': '.CallActionReceiver', 'android:exported': 'false' } });
    }
    application.service = application.service || [];
    if (!has(application.service, '.CallDeclineTaskService')) {
      application.service.push({ $: { 'android:name': '.CallDeclineTaskService', 'android:exported': 'false' } });
    }
    return config;
  });
}

module.exports = function withCallScreen(config) {
  config = withLockScreenFlags(config);
  config = withCallComponents(config);
  config = withModuleFiles(config);
  config = withPackageRegistered(config);
  return config;
};

module.exports.ACTIVITY_CODE = ACTIVITY_CODE;
module.exports.sources = { moduleSource, packageSource, callStyleSource, callActionSource };
