const { withDangerousMod, withXcodeProject } = require('expo/config-plugins');
const fs = require('fs');
const path = require('path');

// Source: an asset that already ships with the app (assets/sounds/ringtone.wav),
// previously only ever played in-app via expo-av — this plugin is what makes it
// usable as a REAL native notification-channel/APNs sound. Unlike the provider
// app's version of this plugin, there's no accept/reject action-icon handling
// here — direct-request bookings (with their Accept/Reject notification
// actions) are a provider-only concept.
const SOUND_SOURCE = 'assets/sounds/ringtone.wav';
// Android raw resource name — referenced in callManager.ts's ensureCallChannel
// as `sound: 'ringtone'` (no extension). Must be lowercase snake_case.
const ANDROID_RAW_FILENAME = 'ringtone.wav';
// iOS just needs the filename (with extension) bundled at the app's resource
// root; Notifee's `ios.sound` field references it exactly as this string.
const IOS_SOUND_FILENAME = 'ringtone.wav';

/**
 * Copies assets/sounds/ringtone.wav into both native projects at prebuild
 * time. This can't be a one-off manual file copy: android/ and ios/ are
 * gitignored and regenerated by `expo prebuild` (and by every EAS build from
 * source), so anything dropped in by hand is silently wiped on the next
 * build — the copy has to happen as a config plugin mod instead.
 */
function withAndroidNotificationSound(config) {
  return withDangerousMod(config, [
    'android',
    async (config) => {
      const rawDir = path.join(config.modRequest.platformProjectRoot, 'app/src/main/res/raw');
      fs.mkdirSync(rawDir, { recursive: true });
      fs.copyFileSync(
        path.join(config.modRequest.projectRoot, SOUND_SOURCE),
        path.join(rawDir, ANDROID_RAW_FILENAME),
      );
      return config;
    },
  ]);
}

function withIosNotificationSound(config) {
  config = withDangerousMod(config, [
    'ios',
    async (config) => {
      const dest = path.join(
        config.modRequest.platformProjectRoot,
        config.modRequest.projectName,
        IOS_SOUND_FILENAME,
      );
      fs.copyFileSync(path.join(config.modRequest.projectRoot, SOUND_SOURCE), dest);
      return config;
    },
  ]);
  // The physical copy above isn't enough on its own — Xcode only bundles
  // files that are registered in the project as a resource, so it also has
  // to be added to the main target's "Copy Bundle Resources" build phase.
  return withXcodeProject(config, (config) => {
    const project = config.modResults;
    const groupKey = project.findPBXGroupKey({ name: config.modRequest.projectName });
    // addResourceFile unconditionally looks up a PBXGroup literally named
    // "Resources" to rewrite the file's path relative to it, and crashes
    // (null.path) if that group doesn't exist — current RN/Expo Xcode
    // templates no longer create one. Creating an empty placeholder group
    // satisfies the lookup without changing where the file actually lands.
    if (!project.pbxGroupByName('Resources')) {
      project.pbxCreateGroup('Resources', '');
    }
    // findPBXGroupKey({ name: projectName }) is ambiguous — there can be more
    // than one group sharing that name (e.g. an unrelated Expo-modules-
    // provider group with no `path` set), and it isn't guaranteed to return
    // the actual main app group. Registering the file with the project-name
    // folder baked into its own path makes it resolve correctly (relative to
    // SOURCE_ROOT) no matter which group it ends up nested under — matching
    // where it's physically copied above, ios/<projectName>/ringtone.wav.
    const resourcePath = path.join(config.modRequest.projectName, IOS_SOUND_FILENAME);
    if (groupKey && !project.hasFile(resourcePath)) {
      project.addResourceFile(resourcePath, {}, groupKey);
    }
    return config;
  });
}

module.exports = function withNotificationSounds(config) {
  config = withAndroidNotificationSound(config);
  config = withIosNotificationSound(config);
  return config;
};
